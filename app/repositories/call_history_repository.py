def _mask_phone(phone: str, role: str) -> str:
    """Mask phone number for non-admin roles. Last 4 digits visible."""
    if not phone:
        return ""
    if role in ("SUPER_ADMIN", "BUSINESS_OWNER", "ADMIN", "SUPERVISOR"):
        return phone
    # Mask all but last 4
    visible = phone[-4:] if len(phone) >= 4 else phone
    return f"****{visible}"


def _recording_info(call: Call) -> RecordingInfoSchema:
    """Determine recording status and whether it is synthetic (AI TTS replay)."""
    url = call.recording_url or ""

    # No recording at all
    if not url:
        return RecordingInfoSchema(status="not_recorded", is_synthetic=False)

    # Twilio CDN URL — treat as provider recording (real, may have customer voice)
    if url.startswith("http"):
        seg = RecordingSegmentSchema(
            segment_index=0,
            duration_ms=(call.duration_seconds or 0) * 1000,
            format="wav",
            status="ready",
        )
        return RecordingInfoSchema(status="ready", is_synthetic=False, segments=[seg])

    # Local /recordings/ path — check if file exists on disk
    if url.startswith("/recordings/"):
        fname = url.split("/recordings/")[-1]
        fpath = RECORDINGS_DIR / fname
        if fpath.exists() and fpath.stat().st_size > 0:
            # Synthetic if generated by ensure_call_recording (TTS replay)
            is_synthetic = True  # all local recordings are TTS-synthesized
            seg = RecordingSegmentSchema(
                segment_index=0,
                duration_ms=(call.duration_seconds or 0) * 1000,
                format="wav",
                status="ready",
            )
            return RecordingInfoSchema(
                status="synthetic" if is_synthetic else "ready",
                is_synthetic=is_synthetic,
                segments=[seg],
            )

    return RecordingInfoSchema(status="not_recorded", is_synthetic=False)


def _encode_cursor(initiated_at: Optional[datetime], call_id: str) -> str:
    data = {"ts": initiated_at.isoformat() if initiated_at else "", "id": call_id}
    return base64.urlsafe_b64encode(json.dumps(data).encode()).decode()


def _decode_cursor(cursor: str) -> Tuple[Optional[datetime], str]:
    try:
        data = json.loads(base64.urlsafe_b64decode(cursor.encode() + b"==").decode())
        ts = datetime.fromisoformat(data["ts"]) if data.get("ts") else None
        return ts, data.get("id", "")
    except Exception:
        return None, ""


def _build_call_item(
    call: Call,
    campaign_name: Optional[str],
    ai_agent_name: Optional[str],
    human_agent_name: Optional[str],
    customer_name: Optional[str],
    customer_phone: Optional[str],
    role: str,
) -> CallHistoryItemSchema:
    # Resolve which agent is AI vs human based on agent_type
    ai_id = call.agent_id if call.agent_type == "AI_VOICE" else None
    human_id = call.user_id or (call.agent_id if call.agent_type == "HUMAN" else None)

    return CallHistoryItemSchema(
        call_id=call.id,
        direction=call.direction or "OUTBOUND",
        status=call.status or "UNKNOWN",
        customer_name=customer_name or call.client_name or None,
        customer_phone=_mask_phone(customer_phone or call.client_phone or "", role),
        duration_seconds=call.duration_seconds or 0,
        campaign_id=call.campaign_id,
        campaign_name=campaign_name,
        ai_agent_id=ai_id,
        ai_agent_name=ai_agent_name if ai_id else None,
        human_agent_id=human_id,
        human_agent_name=human_agent_name if human_id else None,
        agent_type=call.agent_type or "AI_VOICE",
        started_at=call.initiated_at,
        ended_at=call.ended_at,
        has_transcript=bool(call.transcript and call.transcript.strip()),
        call_result=call.call_result,
        recording=_recording_info(call),
    )


async def get_filter_options(
    db: AsyncSession,
    business_id: str,
    campaign_id: Optional[str] = None,
) -> FilterOptionsSchema:
    """Return filter options narrowed to this tenant.
    If campaign_id is given, narrow agents to those used in that campaign.
    """
    # Campaigns
    camp_rows = (
        await db.execute(
            select(Campaign.id, Campaign.name)
            .where(Campaign.business_id == business_id)
            .order_by(Campaign.name)
        )
    ).all()
    campaigns = [{"id": r.id, "name": r.name} for r in camp_rows]

    # AI agents used in calls for this tenant
    ai_base = (
        select(AIAgent.id, AIAgent.name)
        .join(Call, and_(Call.agent_id == AIAgent.id, Call.agent_type == "AI_VOICE"))
        .where(Call.business_id == business_id)
        .distinct()
    )
    if campaign_id:
        ai_base = ai_base.where(Call.campaign_id == campaign_id)
    ai_rows = (await db.execute(ai_base)).all()
    ai_agents = [{"id": r.id, "name": r.name} for r in ai_rows]

    # Human voice agents (users with role VOICE_AGENT or AGENT) used in calls
    human_base = (
        select(User.id, User.full_name)
        .join(Call, and_(Call.user_id == User.id, Call.agent_type == "HUMAN"))
        .where(Call.business_id == business_id)
        .distinct()
    )
    if campaign_id:
        human_base = human_base.where(Call.campaign_id == campaign_id)
    human_rows = (await db.execute(human_base)).all()
    human_agents = [{"id": r.id, "name": r.full_name or r.id} for r in human_rows]

    # Distinct statuses
    status_rows = (
        await db.execute(
            select(Call.status)
            .where(Call.business_id == business_id)
            .distinct()
        )
    ).scalars().all()

    return FilterOptionsSchema(
        campaigns=campaigns,
        ai_agents=ai_agents,
        human_agents=human_agents,
        statuses=sorted([s for s in status_rows if s]),
        directions=["OUTBOUND", "INBOUND"],
    )


async def list_calls(
    db: AsyncSession,
    business_id: str,
    role: str,
    # Filters
    campaign_ids: Optional[List[str]] = None,
    ai_agent_ids: Optional[List[str]] = None,
    human_agent_ids: Optional[List[str]] = None,
    date_from: Optional[datetime] = None,
    date_to: Optional[datetime] = None,
    direction: Optional[str] = None,
    statuses: Optional[List[str]] = None,
    has_recording: Optional[bool] = None,
    search: Optional[str] = None,
    # Pagination
    cursor: Optional[str] = None,
    limit: int = 25,
) -> CallHistoryListSchema:
    """Keyset-paginated, filtered call list. Single query with LEFT JOINs."""
    limit = min(max(limit, 1), 100)

    # Base query — join Campaign, AIAgent (for AI calls), User (for human calls), Lead
    stmt = (
        select(
            Call,
            Campaign.name.label("campaign_name"),
            AIAgent.name.label("ai_agent_name"),
            User.full_name.label("human_agent_name"),
            Lead.first_name.label("lead_first"),
            Lead.last_name.label("lead_last"),
            Lead.phone.label("lead_phone"),
            Lead.ai_summary.label("ai_summary"),
        )
        .outerjoin(Campaign, Campaign.id == Call.campaign_id)
        .outerjoin(
            AIAgent,
            and_(AIAgent.id == Call.agent_id, Call.agent_type == "AI_VOICE"),
        )
        .outerjoin(
            User,
            and_(User.id == Call.user_id, Call.agent_type == "HUMAN"),
        )
        .outerjoin(Lead, Lead.id == Call.lead_id)
        .where(Call.business_id == business_id)
    )

    # Apply filters
    if campaign_ids:
        stmt = stmt.where(Call.campaign_id.in_(campaign_ids))
    if ai_agent_ids:
        stmt = stmt.where(
            and_(Call.agent_id.in_(ai_agent_ids), Call.agent_type == "AI_VOICE")
        )
    if human_agent_ids:
        stmt = stmt.where(
            or_(
                and_(Call.user_id.in_(human_agent_ids), Call.agent_type == "HUMAN"),
                and_(Call.agent_id.in_(human_agent_ids), Call.agent_type == "HUMAN"),
            )
        )
    if date_from:
        stmt = stmt.where(Call.initiated_at >= date_from)
    if date_to:
        stmt = stmt.where(Call.initiated_at <= date_to)
    if direction:
        stmt = stmt.where(Call.direction == direction.upper())
    if statuses:
        stmt = stmt.where(Call.status.in_([s.upper() for s in statuses]))
    if has_recording is True:
        stmt = stmt.where(
            and_(Call.recording_url.isnot(None), Call.recording_url != "")
        )
    elif has_recording is False:
        stmt = stmt.where(
            or_(Call.recording_url.is_(None), Call.recording_url == "")
        )
    if search:
        # Parameterised LIKE — no string concatenation of user input
        like_term = f"%{search.strip()[:100]}%"
        stmt = stmt.where(
            or_(
                Call.client_name.ilike(like_term),
                Call.client_phone.ilike(like_term),
                Call.id.ilike(like_term),
                Lead.first_name.ilike(like_term),
                Lead.last_name.ilike(like_term),
                Lead.phone.ilike(like_term),
            )
        )

    # Keyset pagination: (initiated_at DESC, id DESC) for stable order
    if cursor:
        cur_ts, cur_id = _decode_cursor(cursor)
        if cur_ts:
            stmt = stmt.where(
                or_(
                    Call.initiated_at < cur_ts,
                    and_(Call.initiated_at == cur_ts, Call.id < cur_id),
                )
            )

    stmt = stmt.order_by(Call.initiated_at.desc(), Call.id.desc()).limit(limit + 1)

    rows = (await db.execute(stmt)).all()

    # Determine if there is a next page
    has_more = len(rows) > limit
    rows = rows[:limit]

    items: List[CallHistoryItemSchema] = []
    for row in rows:
        call: Call = row[0]
        cust_name = None
        cust_phone = None
        if row.lead_first or row.lead_last:
            cust_name = f"{row.lead_first or ''} {row.lead_last or ''}".strip()
        if row.lead_phone:
            cust_phone = row.lead_phone

        items.append(
            _build_call_item(
                call=call,
                campaign_name=row.campaign_name,
                ai_agent_name=row.ai_agent_name,
                human_agent_name=row.human_agent_name,
                customer_name=cust_name,
                customer_phone=cust_phone,
                role=role,
            )
        )

    # Count total (without pagination) — separate lightweight query
    count_stmt = (
        select(func.count(Call.id))
        .outerjoin(Lead, Lead.id == Call.lead_id)
        .where(Call.business_id == business_id)
    )
    # Re-apply same filters for accurate count
    if campaign_ids:
        count_stmt = count_stmt.where(Call.campaign_id.in_(campaign_ids))
    if ai_agent_ids:
        count_stmt = count_stmt.where(
            and_(Call.agent_id.in_(ai_agent_ids), Call.agent_type == "AI_VOICE")
        )
    if statuses:
        count_stmt = count_stmt.where(Call.status.in_([s.upper() for s in statuses]))
    if direction:
        count_stmt = count_stmt.where(Call.direction == direction.upper())
    if has_recording is True:
        count_stmt = count_stmt.where(
            and_(Call.recording_url.isnot(None), Call.recording_url != "")
        )
    elif has_recording is False:
        count_stmt = count_stmt.where(
            or_(Call.recording_url.is_(None), Call.recording_url == "")
        )
    if date_from:
        count_stmt = count_stmt.where(Call.initiated_at >= date_from)
    if date_to:
        count_stmt = count_stmt.where(Call.initiated_at <= date_to)
    if search:
        like_term = f"%{search.strip()[:100]}%"
        count_stmt = count_stmt.where(
            or_(
                Call.client_name.ilike(like_term),
                Call.client_phone.ilike(like_term),
                Call.id.ilike(like_term),
                Lead.first_name.ilike(like_term),
                Lead.last_name.ilike(like_term),
                Lead.phone.ilike(like_term),
            )
        )

    total = (await db.execute(count_stmt)).scalar() or 0

    next_cursor = None
    if has_more and items:
        last = items[-1]
        next_cursor = _encode_cursor(last.started_at, last.call_id)

    return CallHistoryListSchema(items=items, total=total, next_cursor=next_cursor)


async def get_call_detail(
    db: AsyncSession,
    business_id: str,
    call_id: str,
    role: str,
) -> Optional[CallHistoryDetailSchema]:
    """Single call detail with transcript and AI summary."""
    row = (
        await db.execute(
            select(
                Call,
                Campaign.name.label("campaign_name"),
                AIAgent.name.label("ai_agent_name"),
                User.full_name.label("human_agent_name"),
                Lead.first_name.label("lead_first"),
                Lead.last_name.label("lead_last"),
                Lead.phone.label("lead_phone"),
                Lead.ai_summary.label("ai_summary"),
            )
            .outerjoin(Campaign, Campaign.id == Call.campaign_id)
            .outerjoin(
                AIAgent,
                and_(AIAgent.id == Call.agent_id, Call.agent_type == "AI_VOICE"),
            )
            .outerjoin(
                User,
                and_(User.id == Call.user_id, Call.agent_type == "HUMAN"),
            )
            .outerjoin(Lead, Lead.id == Call.lead_id)
            .where(and_(Call.id == call_id, Call.business_id == business_id))
        )
    ).first()

    if not row:
        return None

    call: Call = row[0]
    cust_name = None
    cust_phone = None
    if row.lead_first or row.lead_last:
        cust_name = f"{row.lead_first or ''} {row.lead_last or ''}".strip()
    if row.lead_phone:
        cust_phone = row.lead_phone

    base = _build_call_item(
        call=call,
        campaign_name=row.campaign_name,
        ai_agent_name=row.ai_agent_name,
        human_agent_name=row.human_agent_name,
        customer_name=cust_name,
        customer_phone=cust_phone,
        role=role,
    )

    return CallHistoryDetailSchema(
        **base.model_dump(),
        transcript=call.transcript or None,
        ai_summary=row.ai_summary or None,
        turn_count=call.turn_count or 0,
        call_sid=call.call_sid or None,
        from_number=_mask_phone(call.from_number or "", role),
        to_number=_mask_phone(call.to_number or "", role),
    )
